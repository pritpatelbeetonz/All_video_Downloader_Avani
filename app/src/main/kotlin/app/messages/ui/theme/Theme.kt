/**
 * Root theme. Uses the fixed Figma blue brand scheme by default so the app
 * matches the design on every device. Material You dynamic color is available
 * (opt-in via [dynamicColor]) but **off by default** — a wallpaper-derived
 * palette would override the brand identity the design specifies.
 */
@Composable
fun MessagesTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    dynamicColor: Boolean = false,
    content: @Composable () -> Unit,
) {
    val scheme = resolveColorScheme(darkTheme = darkTheme, dynamicColor = dynamicColor)
    MaterialTheme(
        colorScheme = scheme,
        typography = MessagesTypography,
        content = content,
    )
}

@Composable
private fun resolveColorScheme(darkTheme: Boolean, dynamicColor: Boolean): ColorScheme {
    val canDynamic = dynamicColor && Build.VERSION.SDK_INT >= Build.VERSION_CODES.S
    if (canDynamic) {
        val context = LocalContext.current
        return if (darkTheme) dynamicDarkColorScheme(context)
        else dynamicLightColorScheme(context)
    }
    return if (darkTheme) DarkBlueScheme else LightBlueScheme
}


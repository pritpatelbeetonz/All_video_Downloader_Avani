package app.messages.data.db

import androidx.room.Dao
import androidx.room.Insert
import androidx.room.Query
import app.messages.data.db.entity.ScheduledMessageEntity
import kotlinx.coroutines.flow.Flow

@Dao
interface ScheduledMessageDao {

    @Query("SELECT * FROM scheduled_messages WHERE status = :status ORDER BY scheduledAtMs ASC")
    fun observeByStatus(status: String): Flow<List<ScheduledMessageEntity>>

    @Query("SELECT COUNT(*) FROM scheduled_messages WHERE status = :status")
    fun countByStatus(status: String): Flow<Int>

    @Query("SELECT COUNT(*) FROM scheduled_messages WHERE status = :status")
    suspend fun countByStatusNow(status: String): Int

    @Query("SELECT * FROM scheduled_messages WHERE status = :status ORDER BY scheduledAtMs ASC")
    suspend fun listByStatus(status: String): List<ScheduledMessageEntity>

    @Query("SELECT * FROM scheduled_messages WHERE id = :id")
    suspend fun byId(id: Long): ScheduledMessageEntity?

    /** Returns the new row's autogenerated id — used as the alarm request code. */
    @Insert
    suspend fun insert(entity: ScheduledMessageEntity): Long

    @Query("UPDATE scheduled_messages SET status = :status WHERE id = :id")
    suspend fun updateStatus(id: Long, status: String)

    @Query("UPDATE scheduled_messages SET scheduledAtMs = :atMs WHERE id = :id")
    suspend fun updateTime(id: Long, atMs: Long)

    @Query("DELETE FROM scheduled_messages WHERE id = :id")
    suspend fun delete(id: Long)
}
